import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { fixture } from "./fixture.ts";

export const PREVIEW_NAME = "manager-preview";

/**
 * Writes the real manager drawing preview/fixture.ts to `out` (cmux's sidebars folder by default), and returns where.
 */
export const writePreview = (out = join(homedir(), ".config", "cmux", "sidebars", `${PREVIEW_NAME}.js`)): string => {
  const manager = readFileSync(new URL("../dist/manager.js", import.meta.url), "utf8");
  const mock = JSON.stringify(fixture);
  // Parameters shadow cmux's `data` and `cmux` globals, so the real manager draws the fixture
  // with a frozen clock and its taps go nowhere.
  writeFileSync(
    out,
    [
      "// Generated by preview/build.ts: dist/manager.js drawing preview/fixture.ts. Do not edit.",
      `const MOCK = ${mock};`,
      "((data, cmux) => {",
      manager,
      "})({ workspaces: () => MOCK.workspaces, groups: () => MOCK.groups, clock: () => MOCK.clock }, () => {});",
      "",
    ].join("\n"),
  );
  return out;
};

if (import.meta.main) {
  console.log(`Wrote ${writePreview(process.argv[2])}`);
}
